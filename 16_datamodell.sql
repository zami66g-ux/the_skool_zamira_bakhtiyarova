-- Skapa normaliserade tabeller

--Tabell 1: Utbildningsomrode
CREATE TABLE utbildningsomrade (
    utbildningomrade_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utbildningomrade_name VARCHAR2(128) NOT NULL UNIQUE
);

--Tabelll 2: SUN5-inriktning
CREATE TABLE sun5_inriktning (
    sun5_kod VARCHAR2(26) PRIMARY KEY,
    utbildningomrade_id NUMBER NOT NULL,
    sun5_namn VARCHAR2(128),
    CONSTRAINT fk_sun5_omrade
        FOREIGN KEY (utbildningomrade_id)
        REFERENCES utbildningsomrade(utbildningomrade_id)
);

-- Tabell 3: SEQF
CREATE TABLE seqf (
    seqf_kod NUMBER PRIMARY KEY,
    examenstyp VARCHAR2(128)
);

-- Tabell 4: Utbildningsanordnare
CREATE TABLE utbildningsanordnare (
    anordnare_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(128),
    huvudmannatyp VARCHAR2(26)
);

-- Tabell 5: Lan
CREATE TABLE lan (
    lan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lan_name VARCHAR2(128)
);

-- Tabelll 6: Kommun
CREATE TABLE kommun (
    kommun_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kommun_name VARCHAR2(128),
    lan_id NUMBER,
    CONSTRAINT fk_kommun_lan
        FOREIGN KEY (lan_id)
        REFERENCES lan(lan_id)
);

-- Tabell 7: Ansokan
CREATE TABLE ansokan (
    diarienummer VARCHAR2(26) PRIMARY KEY,
    sun5_kod VARCHAR2(26),
    seqf_kod NUMBER,
    anordnare_id NUMBER,
    utbildningsnamn VARCHAR2(128),
    beslut VARCHAR2(26),
    yh_poang NUMBER(5),
    studieform VARCHAR2(26),
    studietakt_procent NUMBER(5),
    smalt_yrkesomrade VARCHAR2(26),
    sokta_utbildningsomgangar NUMBER(3),
    beviljade_utbildningsomgangar NUMBER(3),
    sokta_platser_totalt NUMBER(5),
    beviljade_platser_totalt NUMBER(5),

    CONSTRAINT fk_ansokan_sun5
        FOREIGN KEY (sun5_kod)
        REFERENCES sun5_inriktning(sun5_kod),

    CONSTRAINT fk_ansokan_seqf
        FOREIGN KEY (seqf_kod)
        REFERENCES seqf(seqf_kod),

    CONSTRAINT fk_ansokan_anordnare
        FOREIGN KEY (anordnare_id)
        REFERENCES utbildningsanordnare(anordnare_id)
);

-- Tabell 8: Ansökan_kommun
CREATE TABLE ansokan_kommun (
    ansokan_kommun_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diarienummer VARCHAR2(26),
    kommun_id NUMBER,

    CONSTRAINT fk_ak_ansokan
        FOREIGN KEY (diarienummer)
        REFERENCES ansokan(diarienummer),

    CONSTRAINT fk_ak_kommun
        FOREIGN KEY (kommun_id)
        REFERENCES kommun(kommun_id)
);


